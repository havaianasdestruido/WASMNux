#!/usr/bin/env python3
"""Emit include/generated/timeconst.h exactly as kernel/time/timeconst.bc does.

The kernel generates timeconst.h by piping CONFIG_HZ into `bc -q`. Bare
containers often lack bc, which stops the build at prepare0 even though the
computation is a handful of integer divisions. This script performs the same
arithmetic, transcribing fmul/fadj/fmuls from kernel/time/timeconst.bc, so the
output is byte-identical to what bc would print for any HZ in range.

Usage:
  gen-timeconst.py <hz>          # write the header to stdout
  echo <hz> | gen-timeconst.py   # bc-compatible: read HZ on stdin
"""

import sys
from math import gcd


def fmul(b, n, d):
    # kernel/time/timeconst.bc: (2^b*n+d-1)/d, scale=0 so integer division.
    return (2 ** b * n + d - 1) // d


def fadj(b, n, d):
    d //= gcd(n, d)
    return 2 ** b * (d - 1) // d


def fmuls(b, n, d):
    s = 0
    while fmul(s, n, d) < 2 ** (b - 1):
        s += 1
    return s


def timeconst(hz):
    p = []
    add = p.append

    add("/* Automatically generated by kernel/time/timeconst.bc */")
    add("/* Time conversion constants for HZ == %d */" % hz)
    add("")
    add("#ifndef KERNEL_TIMECONST_H")
    add("#define KERNEL_TIMECONST_H")
    add("")
    add("#include <linux/param.h>")
    add("#include <linux/types.h>")
    add("")
    add("#if HZ != %d" % hz)
    add('#error "include/generated/timeconst.h has the wrong HZ value!"')
    add("#endif")
    add("")

    if hz < 2:
        add("#error Totally bogus HZ value!")
    else:
        s = fmuls(32, 1000, hz)
        add("#define HZ_TO_MSEC_MUL32\tU64_C(0x%X)" % fmul(s, 1000, hz))
        add("#define HZ_TO_MSEC_ADJ32\tU64_C(0x%X)" % fadj(s, 1000, hz))
        add("#define HZ_TO_MSEC_SHR32\t%d" % s)

        s = fmuls(32, hz, 1000)
        add("#define MSEC_TO_HZ_MUL32\tU64_C(0x%X)" % fmul(s, hz, 1000))
        add("#define MSEC_TO_HZ_ADJ32\tU64_C(0x%X)" % fadj(s, hz, 1000))
        add("#define MSEC_TO_HZ_SHR32\t%d" % s)

        cd = gcd(hz, 1000)
        add("#define HZ_TO_MSEC_NUM\t\t%d" % (1000 // cd))
        add("#define HZ_TO_MSEC_DEN\t\t%d" % (hz // cd))
        add("#define MSEC_TO_HZ_NUM\t\t%d" % (hz // cd))
        add("#define MSEC_TO_HZ_DEN\t\t%d" % (1000 // cd))
        add("")

        s = fmuls(32, 1000000, hz)
        add("#define HZ_TO_USEC_MUL32\tU64_C(0x%X)" % fmul(s, 1000000, hz))
        add("#define HZ_TO_USEC_ADJ32\tU64_C(0x%X)" % fadj(s, 1000000, hz))
        add("#define HZ_TO_USEC_SHR32\t%d" % s)

        s = fmuls(32, hz, 1000000)
        add("#define USEC_TO_HZ_MUL32\tU64_C(0x%X)" % fmul(s, hz, 1000000))
        add("#define USEC_TO_HZ_ADJ32\tU64_C(0x%X)" % fadj(s, hz, 1000000))
        add("#define USEC_TO_HZ_SHR32\t%d" % s)

        cd = gcd(hz, 1000000)
        add("#define HZ_TO_USEC_NUM\t\t%d" % (1000000 // cd))
        add("#define HZ_TO_USEC_DEN\t\t%d" % (hz // cd))
        add("#define USEC_TO_HZ_NUM\t\t%d" % (hz // cd))
        add("#define USEC_TO_HZ_DEN\t\t%d" % (1000000 // cd))

        cd = gcd(hz, 1000000000)
        add("#define HZ_TO_NSEC_NUM\t\t%d" % (1000000000 // cd))
        add("#define HZ_TO_NSEC_DEN\t\t%d" % (hz // cd))
        add("#define NSEC_TO_HZ_NUM\t\t%d" % (hz // cd))
        add("#define NSEC_TO_HZ_DEN\t\t%d" % (1000000000 // cd))
        add("")

    add("#endif /* KERNEL_TIMECONST_H */")
    return "\n".join(p) + "\n"


def main():
    hz = int(sys.argv[1]) if len(sys.argv) > 1 else int(sys.stdin.read().strip())
    sys.stdout.write(timeconst(hz))


if __name__ == "__main__":
    main()
